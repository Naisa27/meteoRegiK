def section_html(section: GuideSection, data_dir: Path | None = None) -> str:
    """Страница раздела: заголовок и текст. data_dir — папка базы этой
    установки: с ней раздел "Где хранятся данные" называет настоящую папку,
    а не правило, по которому она выбирается."""
    if data_dir is None:
        where = _DATA_DIR_DEFAULT
    else:
        where = f"<p>На этом компьютере он лежит в папке:</p>{note(f'<b>{escape(str(data_dir))}</b>')}"
    body = section.body.replace(_DATA_DIR_MARK, where)
    return f"<h1>{escape(section.title)}</h1>{body}"
